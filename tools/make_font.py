def bits(rows):
    out = []
    for r in rows:
        v = 0
        for i, c in enumerate(r):
            if c == '#': v |= 0x40 >> i
        out.append(v)
    out.append(0)
    return out
def full(rows8):  # 8 rows of 8 columns
    return [int(r.replace('#', '1').replace('.', '0'), 2) for r in rows8]
