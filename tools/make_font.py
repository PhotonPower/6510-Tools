def emit(name, glyphs):
    lines = [f"const std::array<Byte, 1024> {name} = {{"]
    for i, gl in enumerate(glyphs):
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in gl) + f",  // {i:3d}")
    lines.append("};")
    return "\n".join(lines)
